function createLocaleSet(locales: Locale[]): ReadonlySet<Locale> {
  return new Set<Locale>([routing.defaultLocale, ...locales]);
}

const routeLocaleOverrides = new Map<string, ReadonlySet<Locale>>([
  ...zhOnlyRoutes.map((route) => [route, createLocaleSet(['zh'])] as const),
  ...zhJaRoutes.map((route) => [route, createLocaleSet(['zh', 'ja'])] as const),
  ...fullyLocalizedSearchRoutes.map(
    (route) =>
      [
        route,
        createLocaleSet([
          'zh',
          'ru',
          'de',
          'fr',
          'pt-BR',
          'es-419',
          'ko',
          'ja',
        ]),
      ] as const
  ),
]);

export function normalizeRoutePath(
  pathname: string | undefined = Routes.Root
): string {
  if (!pathname || pathname === Routes.Root) {
    return Routes.Root;
  }

  const withoutQuery = pathname.split(/[?#]/)[0] || Routes.Root;
  return withoutQuery.length > 1
    ? withoutQuery.replace(/\/+$/, '')
    : withoutQuery;
}

export function isRouteReadyForLocale(
  pathname: string | undefined,
  locale?: Locale | null
): boolean {
  const normalizedPath = normalizeRoutePath(pathname);

  if (!locale || locale === routing.defaultLocale || locale === 'default') {
    return true;
  }

  if (globallyLocalizedRoutes.has(normalizedPath)) {
    return true;
  }

  const localeOverride = routeLocaleOverrides.get(normalizedPath);
  if (localeOverride) {
    return localeOverride.has(locale);
  }

  const readyRoutes = localizedRoutes[locale];
  return readyRoutes?.has(normalizedPath) ?? false;
}

export function getReadyLocalesForPathname(pathname: string): Locale[] {
  return routing.locales.filter((locale) =>
    isRouteReadyForLocale(pathname, locale)
  );
}
